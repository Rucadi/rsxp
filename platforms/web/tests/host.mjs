import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync, symlinkSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { spawn, execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
const binary = resolve(process.argv[2] || new URL('../target/release/rsxp-web', import.meta.url).pathname);
const temp = mkdtempSync(join(tmpdir(), 'rsxp-web-host-'));
let server;
try {
  const game = join(temp, 'Game'); mkdirSync(game); mkdirSync(join(game, 'Data'));
  writeFileSync(join(game, 'Game.ini'), '[Game]\nScripts=Data/Scripts.rxdata');
  writeFileSync(join(game, 'Data/Scripts.rxdata'), 'fixture');
  writeFileSync(join(game, 'Data/large.bin'), Buffer.alloc(900_000, 137));
  writeFileSync(join(temp, 'secret'), 'private');
  symlinkSync(join(temp, 'secret'), join(game, 'escape'));
  const player = join(temp, 'player.html');
  execFileSync(binary, ['export', player]);
  assert.match(readFileSync(player, 'utf8'), /Starting workspace/);
  const embedded = join(game, 'game.html');
  execFileSync(binary, ['embed', game, embedded]);
  const html = readFileSync(embedded, 'utf8');
  const config = JSON.parse(html.match(/globalThis.RSXP_GAME=(.*?);<\/script>/)[1]);
  assert.equal(config.files.length, 3);
  const data = config.files.find(([p]) => p === 'Data/Scripts.rxdata')[1];
  const blocks = [...html.matchAll(/<script id="(rsxp-asset-[^"]+)" type="application\/octet-stream">([^<]*)<\/script>/g)];
  const bytes = new Map(blocks.map(([, id, value]) => [id, Buffer.from(value, 'base64')]));
  assert.equal(Buffer.concat(data.chunks.map(id => bytes.get(id))).toString(), 'fixture');
  assert.ok(blocks.every(([, , value]) => value.length <= 1024 * 1024));
  const large = config.files.find(([p]) => p === 'Data/large.bin')[1];
  assert.equal(large.chunks.length, 2);
  assert.deepEqual(Buffer.concat(large.chunks.map(id => bytes.get(id))), Buffer.alloc(900_000, 137));
  server = spawn(binary, ['serve', game, '--port', '0']);
  const url = await new Promise((resolve, reject) => { server.stdout.once('data', data => resolve(data.toString().match(/http:\/\/[^\s]+/)[0])); server.once('error', reject); });
  assert.equal(await (await fetch(url + 'game/data/scripts.rxdata')).text(), 'fixture');
  assert.match(await (await fetch(url)).text(), /globalThis.RSXP_GAME=/);
  for (const path of ['game/%2e%2e%2fsecret', 'game/escape', 'game/%00', 'game/.hidden']) assert.equal((await fetch(url + path)).status, 404);
  assert.equal((await fetch(url + 'game/Game.ini', { method: 'HEAD' })).headers.get('cross-origin-embedder-policy'), 'require-corp');
  console.log('WEB_HOST_SMOKE_OK');
} finally { server?.kill(); rmSync(temp, { recursive: true, force: true }); }
